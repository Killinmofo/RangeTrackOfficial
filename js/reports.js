'use strict';
function reportResult(status){
 if(status==='Qualified'||status==='Expert'||status==='Pass')return 'PASS';
 if(status==='Fail')return 'FAIL';
 return 'INCOMPLETE';
}
function reportTableResult(p,t){
 const value=reportResult(effectiveTableStatus(p,t));
 const usedRefire=refireEligible(p,t)&&tableStatus(p,'refire',t)!=='Incomplete';
 return usedRefire&&value==='PASS'?'PASS (R)':value;
}
function exportRows(){
 // Use the same concise fields as the Summary screen's Detailed Breakdown.
 const session=current();
 const headers=['Shooter','Lane','Butt #','Weapon SN','Total Score','Pass / Fail'];
 const rows=session.shooters.map(p=>{
  const score=effectivePaperTotal(p);
  return [p.name,p.lane??'',p.buttNumber||'',p.weaponSerial||'',score===''?'':score,reportResult(overallStatus(p))];
 });
 return {headers,rows};
}
function reportCounts(){
 const shooters=current().shooters;
 const passed=shooters.filter(p=>reportResult(overallStatus(p))==='PASS').length;
 const failed=shooters.filter(p=>reportResult(overallStatus(p))==='FAIL').length;
 return {count:shooters.length,passed,failed,incomplete:shooters.length-passed-failed};
}
function reportHTML(){
 const {headers,rows}=exportRows(),stats=reportCounts(),session=current();
 const rate=stats.count?Math.round(stats.passed/stats.count*100):0;
 const header=`<div class="report-heading"><h2>RangeTrack | Qualification Summary</h2><p><strong>${safe(db.weapon)} • ${safe(session.template?.name||db.course)}</strong> &nbsp; | &nbsp; ${safe(session.date||'—')}</p><p>Class Summary &nbsp; | &nbsp; Shooters: <strong>${stats.count}</strong> &nbsp; Passed: <strong>${stats.passed}</strong> &nbsp; Failed: <strong>${stats.failed}</strong> &nbsp; Incomplete: <strong>${stats.incomplete}</strong> &nbsp; Pass Rate: <strong>${rate}%</strong></p></div>`;
 const cols=`<thead><tr>${headers.map(h=>`<th>${safe(h)}</th>`).join('')}</tr></thead>`;
 const body=rows.map(row=>`<tr>${row.map((value,j)=>{
  const v=value===''?'—':value;
  const cls=j===headers.length-1?(v==='PASS'?' result-pass':v==='FAIL'?' result-fail':''):'';
  return `<td data-label="${safe(headers[j])}" class="${cls}">${safe(v)}</td>`;
 }).join('')}</tr>`).join('')||`<tr><td colspan="${headers.length}">No shooters added.</td></tr>`;
 return `${header}<div class="report-table-wrap"><table class="report-table">${cols}<tbody>${body}</tbody></table></div>`;
}
function reportFilename(ext){
 const s=current();const name=(db.weapon+'_'+(s.template?.name||db.course)+'_'+(s.date||'class')).replace(/[^a-z0-9_-]+/gi,'_').replace(/_+/g,'_').slice(0,95);
 return 'RangeTrack_'+name+'.'+ext;
}
function exportExcel(){
 const {headers,rows}=exportRows();
 // UTF-8 BOM improves Excel handling of names and symbols; quoted CSV preserves commas and line breaks.
 const csv=[headers,...rows].map(row=>row.map(value=>{
  let v=String(value??'');
  // Prevent spreadsheet formula execution for untrusted names and editable labels.
  if(/^[\s]*[=+@-]/.test(v))v="'"+v;
  return '"'+v.replace(/"/g,'""')+'"';
 }).join(',')).join('\r\n');
 const blob=new Blob(['\ufeff',csv],{type:'text/csv;charset=utf-8;'});
 const url=URL.createObjectURL(blob),a=document.createElement('a');a.href=url;a.download=reportFilename('csv');document.body.appendChild(a);a.click();a.remove();setTimeout(()=>URL.revokeObjectURL(url),2000);
}
